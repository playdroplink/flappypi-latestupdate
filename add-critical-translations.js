// Function to add translations to the file
function addTranslationsToFile() {
  try {
    const content = fs.readFileSync('src/constants/translations.ts', 'utf8');
    let newContent = content;
    
    // For each language, add the missing translations
    Object.keys(criticalTranslations).forEach(key => {
      const translations = criticalTranslations[key];
      
      Object.keys(translations).forEach(langCode => {
        const translation = translations[langCode];
        
        // Find the language section and add the translation
        const langPattern = new RegExp(`(\\s+${langCode}:\\s*\\{[^}]*?)(\\s+\\},)`, 's');
        const replacement = `$1\n    ${key}: "${translation}",$2`;
        
        if (newContent.match(langPattern)) {
          newContent = newContent.replace(langPattern, replacement);
        }
      });
    });
    
    // Write the updated content back to the file
    fs.writeFileSync('src/constants/translations.ts', newContent);
    console.log('✅ Critical translations added successfully!');
    
  } catch (error) {
    console.error('❌ Error adding translations:', error);
  }
}

